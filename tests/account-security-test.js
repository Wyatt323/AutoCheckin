// Persistent policy, safe public views and cooldowns with no network calls.
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {createAccountSecurity,DEFAULTS}=require('../account_security');
const {scopedStore}=require('../database');
(async()=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'account-security-'));
  let time=Date.now(),calls=0,devices=[{hash:'0',current:true,device:'AutoCheckin'},{hash:'9123456789012345678',current:false,device:'My phone'}],response=null,fail=false;
  const docs=new Map(),notices=[];
  const store={read:key=>docs.get(key),write:async(key,value)=>{if(fail)throw Error('injected persistent failure');docs.set(key,structuredClone(value));},keys:()=>[...docs.keys()]};
  const execute=async(account,action,args)=>{
    calls++;
    if(response)return response;
    if(action==='terminate')devices=devices.filter(device=>device.hash!==args.hash);
    return {status:'reachable',detail:'offline read',userId:'123',twoFactor:false,recoveryEmail:false,devices,terminated:action==='terminate',secret:'must-not-appear'};
  };
  const options={dataDir:root,readAccounts:()=>[{session:'first',name:'First',sessionReady:true}],execute,notify:async notice=>{notices.push(notice);return true;},notificationReady:()=>true,now:()=>time};
  let security=await createAccountSecurity({...options,store});
  try {
    await security.update({...DEFAULTS,enabled:true,alertsEnabled:true});
    await security.tick();
    let view=security.view(),row=view.accounts[0];
    assert.equal(row.devices.length,2);assert.equal(row.issues.length,2);
    assert.ok(row.devices[0].trusted);assert.ok(!row.devices[1].trusted);
    assert.ok(!JSON.stringify(view).includes('9123456789012345678'));
    assert.ok(!JSON.stringify(view).includes('must-not-appear'));
    assert.equal(notices.length,1,'initial unconfirmed devices and disabled 2FA are reported');
    assert.throws(()=>security.startCheck('first'),/冷却/);
    time+=61000;security.startCheck('first');
    while(security.view().checking)await new Promise(resolve=>setTimeout(resolve,5));
    assert.equal(notices.length,1,'unchanged warnings are deduplicated');
    devices.push({hash:'-8123456789012345678',device:'New laptop'});
    time+=61000;security.startCheck('first');while(security.view().checking)await new Promise(resolve=>setTimeout(resolve,5));
    assert.equal(notices.length,2,'new device bypasses the unchanged warning cooldown');
    row=security.view().accounts[0];
    await security.trust('first',row.devices[1].id);
    assert.ok(security.view().accounts[0].devices[1].trusted);
    await assert.rejects(security.terminate('first',row.devices[0].id),/当前会话/);
    await assert.rejects(security.terminate('other',row.devices[1].id),/不存在/);
    await security.terminate('first',row.devices[2].id);
    assert.equal(security.view().accounts[0].devices.length,2);
    response={status:'rate_limited',detail:'wait',waitSeconds:7200};time+=61000;
    security.startCheck('first');while(security.view().checking)await new Promise(resolve=>setTimeout(resolve,5));
    const count=calls;time+=3600000;await security.tick();assert.equal(calls,count,'Telegram wait overrides the configured interval');
    assert.throws(()=>security.startCheck('first'),/冷却/);
    await security.stop();security=await createAccountSecurity({...options,store});
    assert.equal(security.view().accounts[0].status,'rate_limited');
    assert.ok(security.view().accounts[0].devices[1].trusted,'confirmed devices survive restart');
    await assert.rejects(security.terminate('first',row.devices[1].id),/限流/);
    fail=true;await assert.rejects(security.update({...DEFAULTS,enabled:false}),/persistent/);assert.ok(security.view().settings.enabled);fail=false;
    const second=await createAccountSecurity({...options,store:scopedStore(store,'tenant:second:')});
    assert.equal(second.view().accounts[0].devices.length,0);assert.equal(second.view().settings.enabled,false);
    await second.update({...DEFAULTS,intervalMinutes:120});assert.equal(security.view().settings.intervalMinutes,60);
    await second.stop();
    const file=await createAccountSecurity({...options,store:null});await file.update({...DEFAULTS,intervalMinutes:90});await file.stop();
    const reload=await createAccountSecurity({...options,store:null});assert.equal(reload.view().settings.intervalMinutes,90);await reload.stop();
    let busyAccount=true,attempts=0;
    const deferred=await createAccountSecurity({...options,store:scopedStore(store,'tenant:deferred:'),execute:async()=>{attempts++;return busyAccount ? {skipped:true,detail:'busy'} : {status:'reachable',detail:'offline check',devices:[]};}});
    await deferred.update({...DEFAULTS,enabled:true});await deferred.tick();
    assert.equal(deferred.view().accounts[0].status,'unchecked','a busy account is not labelled offline');
    time+=30000;await deferred.tick();assert.equal(attempts,1);
    time+=31000;busyAccount=false;await deferred.tick();assert.equal(attempts,2,'busy checks retry after a minute, without waiting an entire inspection interval');
    assert.equal(deferred.view().accounts[0].status,'reachable');await deferred.stop();
    console.log('Account security PASS: private/sanitized views, explicit device actions, current-session protection, alerts/dedup, cooldown/restart, tenant/file/database persistence and failed-write rollback');
  }finally{await security.stop();fs.rmSync(root,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exitCode=1;});
