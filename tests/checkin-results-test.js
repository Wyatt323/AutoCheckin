const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const Results = require('../checkin_results');
const {filterRunLogs} = require('../public/run-log');
const {formatRunResult} = require('../telegram_notifications');
const {createRunHistory} = require('../run_history');
const account='alpha', time='2026-10-07T16:50:30Z';
const successes=Array.from({length:15},(_,i)=>({account,bot:i ? 'bot_'+i : '@niubi_bot',name:i ? 'Bot '+i : 'niubi_bot',note:i ? '' : '牛逼',status:'success'}));
const timeout={account,bot:'KLemby_bot',name:'KLemby_bot',note:'',status:'timeout'};
const record={id:'mixed',account,trigger:'scheduled',state:'failed',startedAt:'2026-10-07T16:40:30Z',finishedAt:time,botResults:[...successes,timeout]};
record.lines=record.botResults.map((botResult,id)=>({id,time,account,text:Results.resultLine(botResult),botResult,stream:botResult.status==='timeout' ? 'stderr' : 'stdout'}));
let summary=Results.summarize(record,account);
assert.equal(summary.state,'partial');assert.equal(summary.counts.success,15);assert.equal(summary.counts.timeout,1);
assert.equal(Results.resultLine(successes[0]),'✅ 牛逼（niubi_bot）');
assert.equal(Results.resultLine({...timeout,note:'测试'}),'⏰ 测试（KLemby_bot）：超时');
const rows=filterRunLogs([record],{account,status:'partial'});
assert.equal(rows.length,16);assert.equal(rows[0].text,'✅ 牛逼（niubi_bot）');
assert.equal(filterRunLogs([record],{status:'failed'}).length,0);
const text=formatRunResult(record,'Wyatt');
assert.match(text,/签到部分成功/);assert.match(text,/共 16 个 · 成功 15 · 超时 1 · 失败 0/);
assert.ok(text.indexOf('⏰ KLemby_bot')<text.indexOf('✅ 牛逼（niubi_bot）'));
assert.match(text,/2026-10-08 00:50:30（北京时间）/);assert.match(text,/10 分 0 秒/);
assert.doesNotMatch(text,/运行失败/);
const legacy={...record,botResults:undefined,lines:[{account,time,text:'  niubi_bot -> 🎉 签到成功'},{account,time,text:'KLemby_bot -> ⏰ 超时'}]};
assert.equal(Results.summarize(legacy,account).state,'partial');
assert.equal(filterRunLogs([legacy],{},[{session:account,bots:[{name:'@NIUBI_bot',note:'牛逼'}]}])[0].text,'✅ 牛逼（niubi_bot）');
assert.equal(Results.summarize({...record,state:'running'},account).state,'running');
assert.equal(Results.summarize({...record,state:'stopped'},account).state,'stopped');
assert.equal(Results.summarize({...record,state:'completed',botResults:successes},account).label,'全部成功');
assert.equal(Results.summarize({...record,botResults:successes},account).label,'任务异常','cleanup error is not concealed');
assert.equal(Results.summarize({...record,botResults:[timeout]},account).state,'failed');
assert.equal(Results.summarize({...record,state:'completed',botResults:[{...timeout,status:'skipped'}]},account).label,'无可签到 Bot');
assert.equal(Results.resultLine({...successes[0],status:'already'}),'✅ 牛逼（niubi_bot）：已签到');
const large=formatRunResult({...record,botResults:Array.from({length:2000},(_,i)=>({...successes[0],bot:'bot_'+i,name:'Bot '+i,note:'备注'.repeat(100)}))});
assert.ok(large.length<=3500);assert.match(large,/另有/);assert.match(large,/结束时间/);
const independent=formatRunResult({...record,bot:'@niubi_bot',botResults:[successes[0]],state:'completed'});
assert.match(independent,/Bot 独立定时 · 牛逼（niubi_bot）/);
const root=fs.mkdtempSync(path.join(os.tmpdir(),'checkin-result-'));
try {
  const history=createRunHistory(root),run=history.create(null,'manual');
  Object.assign(run,{...record,account:null,accountStates:{alpha:'failed',beta:'completed'},botResults:[...record.botResults,{...successes[0],account:'beta',note:'private beta'}]});
  run.lines.push({account:'beta',time,text:'private beta'});history.changed(true);
  const restored=createRunHistory(root).snapshot({account:'alpha'}).records[0];
  assert.equal(restored.botResults.length,16);assert.ok(restored.botResults.every(item=>item.account==='alpha'));
  assert.ok(!JSON.stringify(restored).includes('private beta'));
  assert.equal(Results.summarize(restored,account).state,'partial');
  assert.equal(filterRunLogs([run],{account:'beta',status:'completed'}).length,1,'batch status derives from the selected account');
} finally {fs.rmSync(root,{recursive:true,force:true});}
console.log('Check-in results PASS: remarks, 15/16 partial success, legacy logs, state filtering, notifications, bounds, persistence and batch isolation');
